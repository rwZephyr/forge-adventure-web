"""Hash original compilation inputs and derive constructor metadata from original source."""
from pathlib import Path
import hashlib
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[3]
EXPERIMENT = ROOT / "experiments/rules-teavm"
BASELINE = "db893dcdb14fdd85a05437ad458dc70ef704ca2e"

def main():
    inputs = []
    for module in ["forge-core", "forge-game"]:
        source = ROOT / module / "src/main/java"
        classes = ROOT / module / "target/classes"
        if not classes.is_dir():
            raise RuntimeError("Missing original compilation output: " + str(classes))
        if subprocess.check_output(["git", "diff", BASELINE, "--", str(source)], cwd=ROOT).strip():
            raise RuntimeError("Original source differs from pinned baseline: " + module)
        for folder in [source, classes]:
            for path in sorted(folder.rglob("*")):
                if path.is_file():
                    inputs.append({"path": path.relative_to(ROOT).as_posix(), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    for name in ["pom.xml", "forge-core/pom.xml", "forge-game/pom.xml"]:
        inputs.append({"path": name, "sha256": hashlib.sha256((ROOT / name).read_bytes()).hexdigest()})
    original = ROOT / "forge-game/src/main/java/forge/game"
    trigger_text = (original / "trigger/TriggerType.java").read_text(encoding="utf-8")
    mappings = re.findall(r"^\s*(\w+)\s*\(\s*(\w+)\.class\s*\)", trigger_text, re.M)
    if len(mappings) != 149 or len({cls for _, cls in mappings}) != 137:
        raise RuntimeError("Trigger mapping changed; review the bounded manifest")
    constructors = {"forge.game.trigger." + cls: "java.util.Map,forge.game.card.Card,boolean" for _, cls in mappings}
    for cls in ["ReplaceDraw", "ReplaceGainLife"]:
        constructors["forge.game.replacement." + cls] = "java.util.Map,forge.game.card.Card,boolean"
    keyword_text = (original / "keyword/Keyword.java").read_text(encoding="utf-8")
    for constant, cls in [("FLYING", "SimpleKeyword"), ("BUSHIDO", "KeywordWithAmount"), ("ENCHANT", "KeywordWithType"), ("MULTIKICKER", "KeywordWithCost"), ("KICKER", "Kicker")]:
        if not re.search(r"^\s*" + constant + r'\("[^"]*", ' + cls + r"\.class", keyword_text, re.M):
            raise RuntimeError("Keyword mapping changed: " + constant)
        constructors["forge.game.keyword." + cls] = ""
    manifest = "# Original constructor allowlist; generated by scripts/prepare_inputs.py\n"
    manifest += "".join(cls + "\t" + signature + "\n" for cls, signature in sorted(constructors.items()))
    (EXPERIMENT / "reflection-constructors.tsv").write_text(manifest, encoding="utf-8", newline="\n")
    build = EXPERIMENT / "build"
    build.mkdir(exist_ok=True)
    (build / "trigger-mappings.json").write_text(json.dumps(dict(mappings), indent=2) + "\n", encoding="utf-8")
    jvm_results = build / "jvm-results.json"
    if jvm_results.is_file():
        rows = json.loads(jvm_results.read_text(encoding="utf-8"))["cases"]
        names = next(row for row in rows if row["id"] == "enum.trigger")["observations"]["names"]
        if set(names) != set(dict(mappings)):
            raise RuntimeError("Source mapping does not cover every actual JVM TriggerType constant")
    (build / "input-manifest.json").write_text(json.dumps({"baseline": BASELINE, "inputs": inputs}, indent=2) + "\n", encoding="utf-8")
    print(f"Hashed {len(inputs)} original source/class/POM inputs; {len(constructors)} constructor signatures.")

if __name__ == "__main__":
    main()
