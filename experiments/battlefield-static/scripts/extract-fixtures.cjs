const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '../../..');
const source = 'docs/experiments/evidence/stage-c-dto-20261018/dto-final-2/console.log';
const text = fs.readFileSync(path.join(root, source), 'utf8').replace(/\r\n/g, '\n');
const list = value => value ? value.split(', ') : [];
const capture = (line, pattern) => { const m = line.match(pattern); assert(m, `Unrecognized published frame: ${pattern}`); return m; };
const frames = new Map();
for (const [index, line] of text.split('\n').entries()) {
  if (!line.startsWith('[browser-frame] ')) continue;
  const [, match, session, revision, turn, phase] = capture(line, /Frame\[match=([^,]+), session=([^,]+), revision=(\d+), turn=(\d+), phase=([^,]+),/);
  const players = [...line.matchAll(/Seat\[handle=([^,]+), self=(true|false), life=(\d+)\]/g)]
    .map(([, handle, self, life]) => ({ handle, self: self === 'true', life: +life }));
  const cards = [...line.matchAll(/Face\[handle=([^,]+), name=([^,]+), zone=([^,]+), controller=([^,]+), tapped=(true|false)\]/g)]
    .map(([, handle, name, zone, controller, tapped]) => ({ handle, name, zone, controller, tapped: tapped === 'true' }));
  const stack = [...line.matchAll(/StackFace\[source=([^,]+), targets=\[([^\]]*)\]\]/g)]
    .map(([, source, targets]) => ({ source, targets: list(targets) }));
  const cost = line.match(/payment=Payment\[remaining=\[([^\]]*)\], redPool=(\d+)\]/);
  const payment = cost ? { remaining: list(cost[1]), redPool: +cost[2] } : null;
  const [, id, kind, spell, selected, min, max] = capture(line, /prompt=Decision\[id=([^,]+), kind=([^,]+), source=([^,]*), selected=\[([^\]]*)\], min=(\d+), max=(\d+), choices=/);
  const choices = [...line.matchAll(/Choice\[id=([^,]+), operation=([^,]+), entity=([^\]]*)\]/g)]
    .map(([, id, operation, entity]) => ({ id, operation, entity }));
  assert.equal(players.length, 2); assert.equal(cards.length, 2); assert(choices.length);
  assert(cards.every(c => ['Mountain', 'Lightning Bolt'].includes(c.name)), 'Only the demonstrated two-card fixture');
  assert(choices.every(c => ['cast', 'target', 'mana', 'pass'].includes(c.operation)));
  const frame = { match, session, revision: +revision, turn: +turn, phase, players, cards, stack, payment,
    prompt: { id, kind, source: spell, selected: list(selected), min: +min, max: +max, choices } };
  frames.set(+revision, { sourceLine: index + 1, frame });
}
const views = [
  ['before-cast', 'Before cast', 3], ['target', 'Choose a target', 4],
  ['payment', 'Pay with Mountain', 5], ['stack', 'Spell on the stack', 6],
  ['resolved', 'After resolution', 7]
];
const data = {
  source: { path: source, commit: 'a8c7e0dde0882b27770844500a50253ede39fd90',
    sha256Lf: createHash('sha256').update(text).digest('hex') },
  snapshots: views.map(([key, label, revision]) => { assert(frames.has(revision)); return { key, label, ...frames.get(revision) }; })
};
const output = '// Generated by scripts/extract-fixtures.cjs from published original Forge DTO evidence.\n'
  + '// Static, disconnected snapshots; these handles do not authorize a live match.\n'
  + 'window.FORGE_FIXTURES = ' + JSON.stringify(data, null, 2) + ';\n';
const destination = path.resolve(__dirname, '../fixtures.js');
if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(destination, 'utf8').replace(/\r\n/g, '\n'), output);
  console.log('PASS: five fixture frames exactly match the published source transcription.');
} else {
  fs.writeFileSync(destination, output);
  console.log('Wrote fixtures.js: published revisions 3–7, unchanged handles and choices.');
}
